def normalize_destination(destination):
    destination = destination.lower().strip()

    if "goa" in destination:
        return "goa"

    if "mumbai" in destination:
        return "mumbai"

    return destination


def get_all_places(destination="goa"):
    key = normalize_destination(destination)
    return DESTINATION_PLACES.get(key, [])


def get_place_by_id(place_id, destination="goa"):
    for place in get_all_places(destination):
        if place["id"] == place_id:
            return place

    return None


def get_places_by_category(category, destination="goa"):
    return [
        place
        for place in get_all_places(destination)
        if place["category"].lower() == category.lower()
    ]